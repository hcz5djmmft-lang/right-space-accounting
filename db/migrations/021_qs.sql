-- QS and pricing (Adel, 2026-10-13, update 11): the Master BOQ workbook in the system. The technical office engineer fills
-- the calculators' inputs on an estimate; the quantities, the dry cost and the client price are worked out by the app.
-- The rate table holds the unit prices (seeded from the workbook); an estimate copies them when it is created, so old
-- estimates keep the prices they were made with.
create table qs_rates (
  key         text primary key,
  calculator  text not null,
  price       numeric(18,2) not null default 0,
  updated_by  text references users(id),
  updated_at  timestamptz not null default now()
);

create table estimates (
  id            text primary key default gen_random_uuid()::text,
  project_id    text not null references projects(id) on delete cascade,
  rev           int not null default 0,
  status        text not null default 'draft' check (status in ('draft','sent','accepted','rejected','superseded')),
  title         text not null default '',
  area          numeric(12,2),
  inputs        jsonb not null default '{}'::jsonb,
  dry_cost      numeric(18,2) not null default 0,
  client_price  numeric(18,2) not null default 0,
  risk_pct      numeric(5,2) not null default 10,
  margin_pct    numeric(5,2) not null default 20,
  vat_pct       numeric(5,2) not null default 14,
  created_by    text references users(id),
  created_at    timestamptz not null default now(),
  updated_by    text references users(id),
  updated_at    timestamptz not null default now(),
  sent_by       text references users(id),
  sent_at       timestamptz,
  decided_by    text references users(id),
  decided_at    timestamptz,
  decision_note text not null default '',
  unique (project_id, rev)
);
create index on estimates (project_id);

-- the material plan of a project: every material line of the accepted estimate, for procurement (needed-by dates come from planning)
create table material_plan (
  id           bigserial primary key,
  project_id   text not null references projects(id) on delete cascade,
  estimate_id  text references estimates(id) on delete set null,
  calculator   text not null,
  key          text not null,
  no           text not null default '',
  description  text not null,
  size         text not null default '',
  brand        text not null default '',
  unit         text not null default '',
  qty          numeric(18,3) not null default 0,
  price        numeric(18,2) not null default 0,
  amount       numeric(18,2) not null default 0,
  needed_by    date,
  created_at   timestamptz not null default now()
);
create index on material_plan (project_id);

